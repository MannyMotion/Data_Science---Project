def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Manny's goal tracker")
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("done"); p.add_argument("task_id")
    p = sub.add_parser("undo"); p.add_argument("task_id")
    p = sub.add_parser("add"); p.add_argument("goal_id"); p.add_argument("title"); p.add_argument("due")
    sub.add_parser("board")
    a = ap.parse_args(argv)
    data = load()
    if a.cmd == "done":
        cmd_done(data, a.task_id)
    elif a.cmd == "undo":
        cmd_undo(data, a.task_id)
    elif a.cmd == "add":
        cmd_add(data, a.goal_id, a.title, a.due)
    elif a.cmd == "board":
        build_boards(data)
        print(f"  Boards rebuilt: {BOARD_MD.name} + plan/{BOARD_HTML.name}")
        webbrowser.open(BOARD_HTML.as_uri())
    else:
        cmd_status(data)


if __name__ == "__main__":
    main()
