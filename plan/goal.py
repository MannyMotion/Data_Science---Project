"""goal.py - Manny's goal tracker. One source of truth (plan/goals.json), everything else is generated from it.

Commands (run from the repo folder):
    python plan/goal.py                         status: progress per goal + what's due next
    python plan/goal.py done G2.1               tick a task off -> celebration + ACHIEVEMENTS.md + boards updated
    python plan/goal.py undo G2.1               untick a task (mistakes happen)
    python plan/goal.py add G2 "Task title" 2026-11-20    add a task to a goal (date = due date)
    python plan/goal.py board                   rebuild GOAL_BOARD.md + plan/board.html and open the board

Only the Python standard library is used, so it runs anywhere Python 3.9+ does.
Reading this file is also practice: json, argparse, datetime, pathlib, f-strings, list comprehensions.
"""
from __future__ import annotations

import argparse
import html
import json
import sys
import webbrowser
from datetime import date
from pathlib import Path

PLAN = Path(__file__).resolve().parent          # .../plan
ROOT = PLAN.parent                              # the repo folder
GOALS_FILE = PLAN / "goals.json"
BOARD_MD = ROOT / "GOAL_BOARD.md"
BOARD_HTML = PLAN / "board.html"
ACHIEVEMENTS = ROOT / "ACHIEVEMENTS.md"

try:                                            # emoji must not crash the Windows console
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass


# ── load / save ─────────────────────────────────────────────────────────────
def load() -> dict:
    with open(GOALS_FILE, encoding="utf-8") as f:
        return json.load(f)


def save(data: dict) -> None:
    tmp = GOALS_FILE.with_suffix(".tmp")        # write to a temp file first so a crash can't corrupt the real one
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")
    tmp.replace(GOALS_FILE)


# ── small helpers ───────────────────────────────────────────────────────────
def today() -> date:
    return date.today()


def find_goal(data: dict, goal_id: str) -> dict:
    for g in data["goals"]:
        if g["id"].lower() == goal_id.lower():
            return g
    raise SystemExit(f"No goal called {goal_id}. Goals: {', '.join(g['id'] for g in data['goals'])}")


def find_task(data: dict, task_id: str) -> tuple[dict, dict]:
    for g in data["goals"]:
        for t in g["tasks"]:
            if t["id"].lower() == task_id.lower():
                return g, t
    raise SystemExit(f"No task called {task_id}. Run `python plan/goal.py` to see the task IDs.")


def progress(goal: dict) -> tuple[int, int]:
    done = sum(1 for t in goal["tasks"] if t["done"])
    return done, len(goal["tasks"])


def goal_complete(goal: dict) -> bool:
    d, n = progress(goal)
    return n > 0 and d == n


def bar(done: int, total: int, width: int = 20) -> str:
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def days_until(iso: str) -> int:
    return (date.fromisoformat(iso) - today()).days


def open_tasks(data: dict) -> list[tuple[dict, dict]]:
    """Every unfinished task, soonest due date first."""
    items = [(g, t) for g in data["goals"] for t in g["tasks"] if not t["done"]]
    return sorted(items, key=lambda gt: gt[1]["due"])


# ── celebrations ────────────────────────────────────────────────────────────
def celebrate_task(goal: dict, task: dict) -> None:
    d, n = progress(goal)
    print()
    print("  🎉 🎉 🎉  TASK DONE  🎉 🎉 🎉")
    print(f"  {task['id']}  {task['title']}")
    print(f"  {goal['title']}: {bar(d, n)} {d}/{n}")
    print()


def celebrate_goal(goal: dict) -> None:
    print("  ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★")
    print(f"  🏆  GOAL ACHIEVED: {goal['title']}")
    print(f"  🎁  Your reward: {goal.get('celebration', 'pick one!')}")
    print("  ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★ ★")
    print()


def log_achievement(text: str) -> None:
    if not ACHIEVEMENTS.exists():
        ACHIEVEMENTS.write_text("# 🏆 Achievements\n\nEvery win, with the date. Generated by `plan/goal.py` - newest at the bottom.\n\n",
                                encoding="utf-8")
    with open(ACHIEVEMENTS, "a", encoding="utf-8") as f:
        f.write(f"- **{today().isoformat()}** — {text}\n")


# ── commands ────────────────────────────────────────────────────────────────
def cmd_status(data: dict) -> None:
    all_t = [t for g in data["goals"] for t in g["tasks"]]
    done_all = sum(t["done"] for t in all_t)
    print(f"\n  {data['vision']}")
    print(f"  {days_until(data['deadline'])} days to {data['deadline']}   overall {bar(done_all, len(all_t))} {done_all}/{len(all_t)} tasks\n")
    for g in data["goals"]:
        d, n = progress(g)
        mark = "🏆" if goal_complete(g) else "  "
        print(f"  {mark} {g['id']:<3} {bar(d, n, 12)} {d:>2}/{n:<2} {g['title']}")
    print("\n  Next up:")
    for g, t in open_tasks(data)[:6]:
        left = days_until(t["due"])
        when = f"OVERDUE {-left}d" if left < 0 else ("today" if left == 0 else f"in {left}d")
        print(f"    {t['id']:<5} {when:<12} {t['title']}")
    print("\n  Tick one off:  python plan/goal.py done <task id>\n")


def cmd_done(data: dict, task_id: str) -> None:
    goal, task = find_task(data, task_id)
    if task["done"]:
        print(f"  {task['id']} was already done on {task['done_on']}.")
        return
    was_complete = goal_complete(goal)
    task["done"], task["done_on"] = True, today().isoformat()
    save(data)
    log_achievement(f"✅ {task['id']} {task['title']}")
    celebrate_task(goal, task)
    if goal_complete(goal) and not was_complete:
        log_achievement(f"🏆 **GOAL ACHIEVED — {goal['id']} {goal['title']}** (reward: {goal.get('celebration', '')})")
        celebrate_goal(goal)
    build_boards(data)


def cmd_undo(data: dict, task_id: str) -> None:
    goal, task = find_task(data, task_id)
    task["done"], task["done_on"] = False, None
    save(data)
    log_achievement(f"↩️ {task['id']} reopened")
    print(f"  {task['id']} reopened.")
    build_boards(data)


def cmd_add(data: dict, goal_id: str, title: str, due: str) -> None:
    date.fromisoformat(due)                                    # fails loudly on a bad date
    goal = find_goal(data, goal_id)
    nums = [int(t["id"].split(".")[1]) for t in goal["tasks"]] or [0]
    new_id = f"{goal['id']}.{max(nums) + 1}"
    goal["tasks"].append({"id": new_id, "title": title, "due": due, "done": False, "done_on": None})
    save(data)
    print(f"  Added {new_id}: {title} (due {due})")
    build_boards(data)


# ── boards (generated - never edit them by hand) ────────────────────────────
def build_markdown(data: dict) -> str:
    all_t = [t for g in data["goals"] for t in g["tasks"]]
    done_all = sum(t["done"] for t in all_t)
    lines = [
        "# 🎯 Goal Board",
        "",
        f"> {data['vision']}",
        "",
        f"**{days_until(data['deadline'])} days to {data['deadline']}** · overall `{bar(done_all, len(all_t))}` "
        f"**{done_all}/{len(all_t)} tasks** · updated {today().isoformat()}",
        "",
        "_Generated by `python plan/goal.py` from `plan/goals.json` — don't edit by hand._",
        "",
        "| | Goal | Progress | Target |",
        "|---|---|---|---|",
    ]
    for g in data["goals"]:
        d, n = progress(g)
        mark = "🏆" if goal_complete(g) else "⬜"
        lines.append(f"| {mark} | **{g['id']}** {g['title']} | `{bar(d, n, 10)}` {d}/{n} | {g['target_date']} |")
    for g in data["goals"]:
        d, n = progress(g)
        lines += ["", f"## {'🏆 ' if goal_complete(g) else ''}{g['id']} · {g['title']} ({d}/{n})", "", f"_{g['why']}_", ""]
        for t in g["tasks"]:
            tick = f"✅ ~~{t['title']}~~ — done {t['done_on']}" if t["done"] else f"⬜ {t['title']} — due {t['due']}"
            lines.append(f"- `{t['id']}` {tick}")
    return "\n".join(lines) + "\n"


def build_html(data: dict) -> str:
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    wins = ""
    if ACHIEVEMENTS.exists():
        rows = [l[2:] for l in ACHIEVEMENTS.read_text(encoding="utf-8").splitlines() if l.startswith("- ")]
        wins = json.dumps([html.escape(r.replace("**", "")) for r in rows[-12:]][::-1], ensure_ascii=False)
    else:
        wins = "[]"
    return HTML_TEMPLATE.replace("__DATA__", payload).replace("__WINS__", wins).replace("__TODAY__", today().isoformat())


def build_boards(data: dict) -> None:
    BOARD_MD.write_text(build_markdown(data), encoding="utf-8")
    BOARD_HTML.write_text(build_html(data), encoding="utf-8")


